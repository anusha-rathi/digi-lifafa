import { readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const postsDir = join(root, "src", "lib", "posts");
const output = join(root, "src", "lib", "posts.generated.ts");
const filesWithOrder = await Promise.all(
  (await readdir(postsDir))
    .filter((name) => name.endsWith(".ts"))
    .map(async (name) => {
      const source = await import("node:fs/promises").then(({ readFile }) =>
        readFile(join(postsDir, name), "utf8"),
      );
      const match = source.match(/export const postOrder = (\d+);/);
      if (!match) throw new Error(`${name} is missing postOrder`);
      return { name, order: Number(match[1]) };
    }),
);
const files = filesWithOrder
  .sort((a, b) => a.order - b.order || a.name.localeCompare(b.name))
  .map(({ name }) => name);
const imports = files.map((name, index) =>
  `import { post as post${index} } from "./posts/${name}";`,
);
const contents = `/* Generated by scripts/generate-post-index.mjs. Do not edit or commit. */\n${imports.join("\n")}\n\nexport const GENERATED_POSTS = [\n${files.map((_, index) => `  post${index},`).join("\n")}\n];\n`;
await writeFile(output, contents);
console.log(`Generated ${relative(root, output).split(sep).join("/")} from ${files.length} post files.`);
